export function getRandomShariaCapsule() {
  const item = SHARIA_CAPSULES[Math.floor(Math.random() * SHARIA_CAPSULES.length)];
  let text = `📖 <b>${item.field} 🌟</b>\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `📌 <b>العنوان:</b> <b>${item.title}</b>\n\n`;
  text += `${item.content}\n\n`;
  text += `💡 <b>الخلاصة والتطبيق العملي:</b>\n<b>"${item.action_takeaway}"</b> 🎯\n`;
  text += `━━━━━━━━━━━━━━━━━━━━━\n`;
  text += `✨ <i>«مَن يُرِدِ اللهُ بهِ خيراً يُفقِّههُ في الدِّين» (متفق عليه).</i>`;
  return { ...item, formattedText: text };
}
